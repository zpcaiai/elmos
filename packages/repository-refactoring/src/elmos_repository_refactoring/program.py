@dataclass
class Program:
    """Mutable program state: per-repository runs plus a global gate ledger."""

    plan: ProgramPlan
    #: Keyed by (wave_id, repository_id): a provider that appears in the
    #: compatibility wave *and* the cutover wave has two independent states,
    #: and treating them as one is how a program declares a cutover finished
    #: because the compatibility layer shipped.
    runs: dict[tuple[str, str], RepositoryRun] = field(default_factory=dict)
    paused_from: dict[tuple[str, str], RepositoryState] = field(default_factory=dict)
    gates: dict[str, bool] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.runs:
            for wave in self.plan.waves:
                for repository_id in wave.repositories:
                    self.runs[wave.wave_id, repository_id] = RepositoryRun(
                        repository_id=repository_id,
                        wave_id=wave.wave_id,
                        state=RepositoryState.PENDING,
                    )

    def _resolve(self, repository_id: str, wave_id: str) -> tuple[str, str]:
        if wave_id:
            key = (wave_id, repository_id)
            if key not in self.runs:
                raise ContractError(
                    "repository_not_in_wave",
                    f"'{repository_id}' is not scheduled in wave '{wave_id}'",
                )
            return key
        keys = [item for item in self.runs if item[1] == repository_id]
        if not keys:
            raise ContractError(
                "repository_not_in_program",
                f"'{repository_id}' is not scheduled by program '{self.plan.program_id}'",
            )
        if len(keys) > 1:
            raise ContractError(
                "ambiguous_repository_wave",
                f"'{repository_id}' appears in {len(keys)} waves; name the wave explicitly",
                {"waves": sorted(item[0] for item in keys)},
            )
        return keys[0]

    def require(self, repository_id: str, wave_id: str = "") -> RepositoryRun:
        return self.runs[self._resolve(repository_id, wave_id)]

    def advance(
        self,
        repository_id: str,
        state: RepositoryState,
        *,
        wave_id: str = "",
        run_id: str = "",
        status: Status | None = None,
        detail: str = "",
        days_outstanding: int | None = None,
    ) -> RepositoryRun:
        key = self._resolve(repository_id, wave_id)
        current = self.runs[key]
        if current.state is RepositoryState.PAUSED and state is not RepositoryState.PAUSED:
            raise ContractError(
                "repository_paused",
                f"'{repository_id}' is paused; resume it before advancing it",
            )
        updated = RepositoryRun(
            repository_id=repository_id,
            wave_id=current.wave_id,
            state=state,
            run_id=run_id or current.run_id,
            status=status or current.status,
            detail=detail or current.detail,
            days_outstanding=current.days_outstanding if days_outstanding is None else days_outstanding,
        )
        self.runs[key] = updated
        return updated

    def pause(self, repository_id: str, *, reason: str, wave_id: str = "") -> RepositoryRun:
        """Pause one repository in one wave, remembering exactly where it was."""

        key = self._resolve(repository_id, wave_id)
        current = self.runs[key]
        if current.state is RepositoryState.PAUSED:
            return current
        self.paused_from[key] = current.state
        updated = RepositoryRun(
            repository_id=repository_id,
            wave_id=current.wave_id,
            state=RepositoryState.PAUSED,
            run_id=current.run_id,
            status=current.status,
            detail=reason,
            days_outstanding=current.days_outstanding,
        )
        self.runs[key] = updated
        return updated

    def resume(self, repository_id: str, *, wave_id: str = "") -> RepositoryRun:
        key = self._resolve(repository_id, wave_id)
        current = self.runs[key]
        if current.state is not RepositoryState.PAUSED:
            return current
        previous = self.paused_from.pop(key, RepositoryState.PENDING)
        updated = RepositoryRun(
            repository_id=repository_id,
            wave_id=current.wave_id,
            state=previous,
            run_id=current.run_id,
            status=current.status,
            detail="",
            days_outstanding=current.days_outstanding,
        )
        self.runs[key] = updated
        return updated

    # -- adjudication ----------------------------------------------------

    def wave(self, wave_id: str) -> ProgramWave:
        for item in self.plan.waves:
            if item.wave_id == wave_id:
                return item
        raise ContractError("unknown_wave", f"program has no wave '{wave_id}'")

    def wave_complete(self, wave_id: str) -> bool:
        wave = self.wave(wave_id)
        return all(
            self.runs[wave.wave_id, repository_id].state in TERMINAL_STATES
            for repository_id in wave.repositories
        )

    def may_start(self, wave_id: str) -> tuple[bool, tuple[str, ...]]:
        """A wave starts only when every wave it requires is fully adopted."""

        wave = self.wave(wave_id)
        blockers: list[str] = []
        for required in wave.requires:
            if not self.wave_complete(required):
                outstanding = [
                    repository_id
                    for repository_id in self.wave(required).repositories
                    if self.runs[required, repository_id].state not in TERMINAL_STATES
                ]
                blockers.append(
                    f"wave '{required}' is not adopted; outstanding: {', '.join(sorted(outstanding))}"
                )
        if wave.destructive:
            stuck = stuck_consumers(self)
            if stuck:
                blockers.append(
                    f"{len(stuck)} consumer(s) have not adopted: "
                    + ", ".join(item["repositoryId"] for item in stuck[:8])
                    + "; removal while any of them still calls the old path is the breakage, "
                    "not the cleanup"
                )
        return (not blockers, tuple(blockers))

    def adoption_report(self) -> dict[str, Any]:
        by_state: dict[str, int] = {}
        for run in self.runs.values():
            by_state[run.state.value] = by_state.get(run.state.value, 0) + 1
        total = len(self.runs) or 1
        adopted = sum(1 for run in self.runs.values() if run.state in TERMINAL_STATES)
        return {
            "programId": self.plan.program_id,
            "repositoryCount": len({key[1] for key in self.runs}),
            "scheduledSlots": len(self.runs),
            "adopted": adopted,
            "adoptionRate": str((Decimal(adopted) / Decimal(total)).quantize(Decimal("0.0001"))),
            "byState": dict(sorted(by_state.items())),
            "stuckConsumers": list(stuck_consumers(self)),
            "waves": [
                {
                    **wave.to_payload(),
                    "complete": self.wave_complete(wave.wave_id),
                    "mayStart": self.may_start(wave.wave_id)[0],
                    "blockers": list(self.may_start(wave.wave_id)[1]),
                }
                for wave in self.plan.waves
            ],
        }

    def to_payload(self) -> dict[str, Any]:
        return {
            "plan": self.plan.to_payload(),
            "runs": [self.runs[key].to_payload() for key in sorted(self.runs)],
            "gates": dict(sorted(self.gates.items())),
            "adoption": self.adoption_report(),
        }


def stuck_consumers(program: Program, *, threshold_days: int = 30) -> tuple[Mapping[str, Any], ...]:
    """Consumers outstanding past the threshold, or unreachable entirely."""

    by_id = {entry.repository_id: entry for entry in program.plan.portfolio}
    stuck: list[Mapping[str, Any]] = []
    for key in sorted(program.runs):
        wave_id, repository_id = key
        run = program.runs[key]
        entry = by_id.get(repository_id)
        if entry is None or entry.role is RepositoryRole.PROVIDER:
            continue
        if run.state in TERMINAL_STATES:
            continue
        reason = ""
        if run.state is RepositoryState.PAUSED:
            reason = f"paused: {run.detail or 'no reason recorded'}"
        elif entry.external:
            reason = "outside this organisation; adoption cannot be scheduled"
        elif run.days_outstanding >= threshold_days:
            reason = f"outstanding for {run.days_outstanding} day(s)"
        elif run.state is RepositoryState.FAILED:
            reason = f"failed: {run.detail or 'no detail recorded'}"
        if reason:
            stuck.append(
                {
                    "repositoryId": repository_id,
                    "waveId": wave_id,
                    "role": entry.role.value,
                    "state": run.state.value,
                    "owners": list(entry.owners),
                    "reason": reason,
                }
            )
    return tuple(stuck)


