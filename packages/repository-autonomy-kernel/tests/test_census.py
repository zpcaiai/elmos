class _RaisingReader:
    """A reader that fails mid-scan, used to provoke non-success statuses."""

    def __init__(self, inner: SnapshotRepositoryReader, error: KernelError) -> None:
        self._inner = inner
        self._error = error

    @property
    def snapshot_sha(self) -> str:
        return self._inner.snapshot_sha

    def list_paths(self) -> Sequence[str]:
        return self._inner.list_paths()

    def read_text(self, path: str) -> str:
        raise self._error

    def read_bytes(self, path: str) -> bytes:
        raise self._error

    def stat(self, path: str) -> Mapping[str, Any]:
        return self._inner.stat(path)


