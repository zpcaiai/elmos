def test_tampered_census_fails_its_own_digest(profile):
    tampered = dict(profile)
    counts = dict(tampered["counts"])
    counts["fileCount"] = counts["fileCount"] + 1
    tampered["counts"] = counts
    recomputed = digest({k: v for k, v in tampered.items() if k != "censusDigest"})
    assert recomputed != profile["censusDigest"]


def test_dropping_a_risk_path_fails_its_own_digest(profile):
    tampered = dict(profile)
    tampered["riskSurface"] = [
        item for item in profile["riskSurface"] if item["path"] != ".env"
    ]
    recomputed = digest({k: v for k, v in tampered.items() if k != "censusDigest"})
    assert recomputed != profile["censusDigest"]


def test_registry_round_trip(reader):
    result = dispatch("repository-census", {"reader": reader})
    assert result.status is Status.SUCCEEDED
    assert result.succeeded
    assert result.outputs["censusDigest"].startswith("sha256:")
    assert set(result.outputs) >= {
        "repositoryProfile", "moduleGraph", "buildGraph", "entrypointMap",
        "dataFlowMap", "riskMap", "definitions", "gates",
    }
