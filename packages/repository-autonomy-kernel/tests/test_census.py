# --- non-negotiable invariants ----------------------------------------------


def test_i1_every_conclusion_binds_to_one_snapshot(reader, profile):
    """I1: all conclusions bound to the same snapshot."""

    assert profile["snapshotSha"] == reader.snapshot_sha
    known = set(reader.list_paths())
    reported = (
        [item["path"] for item in profile["riskSurface"]]
        + [item["path"] for item in profile["buildRoots"]]
        + [item["path"] for item in profile["largestFiles"]]
        + [item["path"] for item in profile["entrypoints"]]
    )
    assert set(reported) <= known


def test_i2_no_conclusion_without_evidence(profile):
    """I2: an unevidenced summary must not enter the authoritative output."""

    for item in profile["generatedSplit"]["generated"]:
        assert item["reason"]
    for item in profile["testSplit"]["test"]:
        assert item["reason"]
    for item in profile["riskSurface"]:
        assert item["markers"]


def test_i3_vendor_generated_and_fixture_are_marked(profile):
    """I3: vendor / generated / test-fixture must be marked."""

    generated = {item["path"]: item["reason"] for item in profile["generatedSplit"]["generated"]}
    assert generated["vendor/left-pad/index.js"].startswith("vendored-directory:")
    assert generated["src/app/schema_pb2.py"] == "generated-filename"
    assert generated["src/app/wire.py"] == "content-marker:do not edit"
    tests = {item["path"]: item["reason"] for item in profile["testSplit"]["test"]}
    assert tests["tests/testdata/sample.txt"].startswith("fixture-directory:")
    assert tests["tests/test_run.py"].startswith("test-directory:")


def test_i4_partial_census_is_explicit_and_never_success(repo):
    """I4: a partial index must say so, and PARTIAL must not widen to SUCCEEDED."""

    reader = SnapshotRepositoryReader(repo, max_file_bytes=8)
    result = census.build_census(reader)
    assert result.status is Status.PARTIAL
    payload = result.to_payload()
    assert payload["status"] == "PARTIAL"
    assert payload["unmeasured"]
    dispatched = dispatch("repository-census", {"reader": reader})
    assert dispatched.status is Status.PARTIAL
    assert not dispatched.succeeded


def test_oversized_file_is_unmeasured_not_zero_lines(repo):
    reader = SnapshotRepositoryReader(repo, max_file_bytes=8)
    payload = census.build_census(reader).to_payload()
    unmeasured = {item["path"]: item for item in payload["unmeasured"]}
    assert "src/app/main.py" in unmeasured
    entry = unmeasured["src/app/main.py"]
    assert entry["lineCount"] is None
    assert entry["lineCountMeasured"] is False
    assert entry["reason"] == "oversized-in-snapshot"
    assert payload["countsMeasured"]["lineCount"] is False


