# --- negative tests ----------------------------------------------------------


def test_negative_malformed_input_is_rejected(reader):
    result = dispatch("repository-census", {"reader": reader, "surpriseField": 1})
    assert result.status is Status.FAILED
    assert result.error["code"] == "UNKNOWN_FIELD"

    missing = dispatch("repository-census", {})
    assert missing.error["code"] == "MISSING_REQUIRED_INPUT"

    wrong_type = dispatch("repository-census", {"reader": object()})
    assert wrong_type.error["code"] == "MALFORMED_INPUT"


def test_negative_stale_snapshot_is_rejected(repo, reader):
    (repo / "src" / "app" / "main.py").write_text("print('changed')\n", encoding="utf-8")
    result = dispatch("repository-census", {"reader": reader})
    assert result.status is Status.FAILED
    assert result.error["code"] == "STALE_SNAPSHOT"


def test_negative_expected_snapshot_mismatch_is_rejected(reader):
    result = dispatch("repository-census",
                      {"reader": reader, "snapshotSha": "sha256:" + "0" * 64})
    assert result.error["code"] == "SNAPSHOT_CHANGED"


def test_negative_partial_is_not_success(repo):
    reader = SnapshotRepositoryReader(repo, max_file_bytes=8)
    strict = dispatch("repository-census", {"reader": reader, "failOnPartial": True})
    assert strict.status is Status.PARTIAL
    assert strict.error["code"] == "PARTIAL_CENSUS"
    assert strict.error["partial"] is True
    assert not strict.succeeded


def test_negative_interrupted_is_not_success(reader):
    interrupted = KernelError(
        code="CANCELLED",
        message="executor interrupted mid-census",
        interrupted=True,
        recommended_action="reconcile before retrying",
    )
    result = dispatch("repository-census", {"reader": _RaisingReader(reader, interrupted)})
    assert result.status is Status.INTERRUPTED
    assert not result.succeeded


