def test_unknown_language_bucket_is_never_folded_away(profile):
    by_marker = {entry["language"]: entry for entry in profile["languageMixByMarker"]}
    by_extension = {entry["language"]: entry for entry in profile["languageMixByExtension"]}
    assert "unknown" in by_marker
    assert "unknown" in by_extension
    # The two views disagree, and the disagreement survives into the output.
    assert by_marker["unknown"]["fileCount"] != by_extension["unknown"]["fileCount"]
    assert by_marker["Python"]["fileCount"] == 1  # only the shebanged file


