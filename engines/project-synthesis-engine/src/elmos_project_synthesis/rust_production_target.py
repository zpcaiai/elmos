_RUSTFMT_MAX_WIDTH = 100


def _string_const(name: str, literal: str) -> str:
    """Emit a ``&str`` constant already laid out the way rustfmt would.

    rustfmt never reflows a string literal; for a `const` it only chooses
    whether the literal shares the line with the binding or moves to the next
    one, and that choice is a pure function of the line width. Reproducing the
    rule here keeps `cargo fmt --check` clean for schemas whose names are long
    enough to push the declaration over the limit.
    """
    single = f"const {name}: &str = {literal};"
    if len(single) <= _RUSTFMT_MAX_WIDTH:
        return single
    # Wrapping only happens when it actually buys something. A literal that
    # overflows even on its own indented line is left where it is, because
    # rustfmt will not break a string to make it fit.
    if len(literal) + 5 <= _RUSTFMT_MAX_WIDTH:
        return f"const {name}: &str =\n    {literal};"
    return single


def _upsert_query(bind_values: list[str], *, sql_const: str = "UPSERT_SQL") -> str:
    """Lay out the upsert `.query(..)` call the way rustfmt would.

    This is the one call whose width genuinely tracks the schema: it binds one
    parameter per field. Below the limit rustfmt keeps it on a single line;
    above it, the call and the parameter slice are both exploded one entry per
    line. Both forms are reproduced here so the emitted workspace is clean
    whatever the entity turns out to look like.
    """
    values = ["&tenant", "&id", *bind_values]
    parameters = ", ".join(values)
    collapsed = (
        f"        let rows = transaction.query({sql_const}, &[{parameters}]).await?;"
    )
    if len(collapsed) <= _RUSTFMT_MAX_WIDTH:
        return collapsed
    broken = f"            .query({sql_const}, &[{parameters}])"
    if len(broken) <= _RUSTFMT_MAX_WIDTH:
        return f"        let rows = transaction\n{broken}\n            .await?;"
    param_line = f"                &[{parameters}],"
    if len(param_line) <= _RUSTFMT_MAX_WIDTH:
        return (
            "        let rows = transaction\n"
            "            .query(\n"
            f"                {sql_const},\n"
            f"{param_line}\n"
            "            )\n"
            "            .await?;"
        )
    entries = "\n".join(f"                    {value}," for value in values)
    return (
        "        let rows = transaction\n"
        "            .query(\n"
        f"                {sql_const},\n"
        "                &[\n"
        f"{entries}\n"
        "                ],\n"
        "            )\n"
        "            .await?;"
    )


def _from_row_body(assignments: list[str]) -> str:
    """Lay out the `Ok(Self { .. })` literal the way rustfmt would.

    A struct literal collapses onto one line while it fits and explodes one
    field per line once it does not, so a one-field entity and a six-field
    entity need different source text for the same template.
    """
    single = "        Ok(Self { " + ", ".join(assignments) + " })"
    if len(single) <= _RUSTFMT_MAX_WIDTH:
        return single
    entries = "\n".join(f"            {assignment}," for assignment in assignments)
    return f"        Ok(Self {{\n{entries}\n        }})"


def _substitute(template: str, replacements: dict[str, str]) -> str:
    rendered = template.lstrip("\n")
    for token, value in replacements.items():
        rendered = rendered.replace(token, value)
    if "__" in rendered:
        leftovers = sorted(
            {
                fragment
                for fragment in rendered.split()
                if fragment.startswith("__") and fragment.endswith("__")
            }
        )
        if leftovers:
            raise ValueError("RUST_TEMPLATE_TOKEN_UNRESOLVED:" + ",".join(leftovers))
    return rendered


