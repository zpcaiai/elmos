def _rust_type(field: FieldSpec) -> str:
    return {
        "string": "String",
        "integer": "i64",
        "number": "f64",
        "boolean": "bool",
        "datetime": "String",
    }[field.type]


def _row_read(field: FieldSpec, index: int) -> str:
    """Read column ``index`` with the type PostgreSQL actually stores."""
    if field.type == "number":
        return f"decimal_to_f64(row.get::<_, Decimal>({index}))?"
    if field.type == "datetime":
        return f"row.get::<_, String>({index})"
    return f"row.get({index})"


def _bind_expression(field: FieldSpec) -> str:
    if field.type == "number":
        return f"&f64_to_decimal(payload.{field.name})?"
    return f"&payload.{field.name}"


