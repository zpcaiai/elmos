"""Axum production profile: PostgreSQL, forced RLS, JWT or OIDC bearer.

Same shared contract and harness as the Python, Java, Go, TypeScript, C# and
Kotlin profiles. The store speaks tokio-postgres directly so the tenant binding
stays visible rather than hidden behind an ORM session.

Rust source is assembled by ``__TOKEN__`` substitution rather than f-strings:
the generated code is dense with braces, and doubling every one of them to
survive ``str.format`` turns a readable template into a defect factory.

Two mappings are not obvious and are load-bearing:

* ``number`` columns are ``numeric(20,6)``. tokio-postgres has no ``f64``
  conversion for PostgreSQL ``NUMERIC``, so the column is read and written as
  ``rust_decimal::Decimal`` and converted at the JSON boundary. Reading it as
  ``f64`` compiles and then panics at runtime on the first row.
* The integration client is hand-rolled over ``std::net::TcpStream``. A real
  HTTP client crate would add a TLS stack to a build that only ever talks to
  127.0.0.1, and every extra crate is another version to pin and audit.
"""
