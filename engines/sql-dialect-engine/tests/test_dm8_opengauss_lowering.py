class TestDM8Lowering:
    """Tests for DM8DialectLowerer."""

    @pytest.fixture
    def lowerer(self) -> DM8DialectLowerer:
        return DM8DialectLowerer()

    def test_dm8_data_type_lowering(self, lowerer: DM8DialectLowerer) -> None:
        """Test PostgreSQL / MySQL / T-SQL data types mapped to DM8."""
        # Postgres serial types
        assert "BIGINT IDENTITY(1, 1)" in lowerer.lower_data_types("id BIGSERIAL PRIMARY KEY")
        assert "INT IDENTITY(1, 1)" in lowerer.lower_data_types("id SERIAL PRIMARY KEY")
        assert "IDENTITY(1, 1)" in lowerer.lower_data_types("id INT GENERATED ALWAYS AS IDENTITY")
        assert "IDENTITY(1, 1)" in lowerer.lower_data_types("id INT GENERATED BY DEFAULT AS IDENTITY")

        # MySQL AUTO_INCREMENT
        assert "IDENTITY(1, 1)" in lowerer.lower_data_types("id INT AUTO_INCREMENT PRIMARY KEY")

        # Boolean -> BIT
        assert "is_active BIT" in lowerer.lower_data_types("is_active BOOLEAN")
        assert "is_active BIT" in lowerer.lower_data_types("is_active BOOL")

        # Text -> CLOB
        assert "bio CLOB" in lowerer.lower_data_types("bio TEXT")
        assert "doc CLOB" in lowerer.lower_data_types("doc LONGTEXT")
        assert "doc CLOB" in lowerer.lower_data_types("doc MEDIUMTEXT")

        # Bytea / Blob -> BLOB
        assert "avatar BLOB" in lowerer.lower_data_types("avatar BYTEA")
        assert "data BLOB" in lowerer.lower_data_types("data LONGBLOB")

        # Timestamps and UUID
        assert "TIMESTAMP WITH TIME ZONE" in lowerer.lower_data_types("created_at TIMESTAMPTZ")
        assert "VARCHAR(36)" in lowerer.lower_data_types("token UUID")

        # JSON/JSONB -> CLOB
        assert "payload CLOB" in lowerer.lower_data_types("payload JSON")
        assert "payload CLOB" in lowerer.lower_data_types("payload JSONB")

    def test_dm8_constraints_lowering(self, lowerer: DM8DialectLowerer) -> None:
        """Test DM8 table constraints preservation."""
        ddl = (
            "CREATE TABLE order_items (\n"
            "  id SERIAL PRIMARY KEY,\n"
            "  order_id INT REFERENCES orders(id) ON DELETE CASCADE,\n"
            "  sku VARCHAR(50) NOT NULL,\n"
            "  quantity INT NOT NULL,\n"
            "  price NUMERIC(10, 2) NOT NULL,\n"
            "  CONSTRAINT uq_order_sku UNIQUE (order_id, sku),\n"
            "  CONSTRAINT chk_qty CHECK (quantity > 0)\n"
            ");"
        )
        lowered = lowerer.lower_ddl(ddl)
        assert "PRIMARY KEY" in lowered
        assert "REFERENCES orders(id) ON DELETE CASCADE" in lowered
        assert "UNIQUE (order_id, sku)" in lowered
        assert "CHECK (quantity > 0)" in lowered
        assert "INT IDENTITY(1, 1)" in lowered

    def test_dm8_sequence_lowering(self, lowerer: DM8DialectLowerer) -> None:
        """Test DM8 sequence creation and NEXTVAL semantics."""
        # Sequence creation
        seq_ddl = "CREATE SEQUENCE seq_orders START WITH 1 INCREMENT BY 1;"
        assert lowerer.lower_sequence(seq_ddl) == seq_ddl

        # nextval('seq_orders') -> seq_orders.NEXTVAL
        query = "SELECT nextval('seq_orders')"
        lowered = lowerer.lower_sequence(query)
        assert "seq_orders.NEXTVAL" in lowered

        # seq_orders.nextval -> seq_orders.NEXTVAL
        query2 = "SELECT seq_orders.nextval FROM DUAL"
        assert "seq_orders.NEXTVAL" in lowerer.lower_sequence(query2)

    def test_dm8_query_functions(self, lowerer: DM8DialectLowerer) -> None:
        """Test DM8 function lowering: NOW -> SYSDATE, IFNULL -> NVL, ILIKE, etc."""
        # NOW() -> SYSDATE, CURRENT_TIMESTAMP -> SYSTIMESTAMP
        assert "SYSDATE" in lowerer.lower_functions("SELECT NOW()")
        assert "SYSTIMESTAMP" in lowerer.lower_functions("SELECT CURRENT_TIMESTAMP")

        # IFNULL / ISNULL -> NVL
        assert "NVL(name, 'default')" in lowerer.lower_functions("SELECT IFNULL(name, 'default')")
        assert "NVL(name, 'default')" in lowerer.lower_functions("SELECT ISNULL(name, 'default')")

        # SUBSTRING -> SUBSTR
        assert "SUBSTR(name, 1, 5)" in lowerer.lower_functions("SELECT SUBSTRING(name FROM 1 FOR 5)")
        assert "SUBSTR(name, 1, 5)" in lowerer.lower_functions("SELECT SUBSTRING(name, 1, 5)")

        # UUID generators -> RAWTOHEX(SYS_GUID())
        assert "RAWTOHEX(SYS_GUID())" in lowerer.lower_functions("SELECT GEN_RANDOM_UUID()")
        assert "RAWTOHEX(SYS_GUID())" in lowerer.lower_functions("SELECT UUID()")
        assert "RAWTOHEX(SYS_GUID())" in lowerer.lower_functions("SELECT NEWID()")

        # ILIKE with default regex_like strategy
        res_default = lowerer.lower_functions("SELECT * FROM t WHERE name ILIKE '%test%'")
        assert "REGEXP_LIKE(name, '%test%', 'i')" in res_default

        # ILIKE with lower strategy
        lower_lowerer = DM8DialectLowerer(ilike_strategy="lower")
        res_lower = lower_lowerer.lower_functions("SELECT * FROM t WHERE name ILIKE '%test%'")
        assert "LOWER(name) LIKE LOWER('%test%')" in res_lower

    def test_dm8_limit_offset_and_dual(self, lowerer: DM8DialectLowerer) -> None:
        """Test LIMIT/OFFSET and FROM DUAL assurance."""
        # ANSI OFFSET ... FETCH ... -> LIMIT ... OFFSET ...
        q1 = "SELECT * FROM orders ORDER BY id OFFSET 20 ROWS FETCH NEXT 10 ROWS ONLY"
        assert "LIMIT 10 OFFSET 20" in lowerer.lower_limit_offset(q1)

        # MySQL LIMIT offset, count -> LIMIT count OFFSET offset
        q2 = "SELECT * FROM orders LIMIT 20, 10"
        assert "LIMIT 10 OFFSET 20" in lowerer.lower_limit_offset(q2)

        # T-SQL TOP n
        q3 = "SELECT TOP 10 id, name FROM users"
        assert "LIMIT 10" in lowerer.lower_limit_offset(q3)

        # FROM DUAL
        assert lowerer.ensure_dual_table("SELECT 1") == "SELECT 1 FROM DUAL"
        assert lowerer.ensure_dual_table("SELECT SYSDATE;") == "SELECT SYSDATE FROM DUAL;"
        assert lowerer.ensure_dual_table("SELECT * FROM users") == "SELECT * FROM users"

        # ROWNUM pagination wrapper
        paged = lowerer.wrap_with_rownum("SELECT id FROM orders", 10, 20)
        assert "ROWNUM <= 30" in paged
        assert "rnum > 20" in paged

    def test_dm8_upsert_mysql_on_duplicate(self, lowerer: DM8DialectLowerer) -> None:
        """Test MySQL ON DUPLICATE KEY UPDATE lowering to MERGE INTO."""
        mysql_sql = (
            "INSERT INTO accounts (id, balance, updated_at) "
            "VALUES (1001, 500.0, NOW()) "
            "ON DUPLICATE KEY UPDATE balance = 500.0, updated_at = NOW();"
        )
        merged = lowerer.lower_upsert(mysql_sql)
        assert merged.startswith("MERGE INTO accounts USING")
        assert "ON (accounts.id = src.id)" in merged
        assert "WHEN MATCHED THEN UPDATE SET" in merged
        assert "balance = 500.0" in merged
        assert "WHEN NOT MATCHED THEN INSERT" in merged

    def test_dm8_upsert_postgres_on_conflict_do_update(self, lowerer: DM8DialectLowerer) -> None:
        """Test PostgreSQL ON CONFLICT DO UPDATE lowering to MERGE INTO."""
        pg_sql = (
            "INSERT INTO products (sku, title, price) "
            "VALUES ('SKU-001', 'Keyboard', 99.99) "
            "ON CONFLICT (sku) DO UPDATE SET title = EXCLUDED.title, price = EXCLUDED.price;"
        )
        merged = lowerer.lower_upsert(pg_sql)
        assert merged.startswith("MERGE INTO products USING")
        assert "ON (products.sku = src.sku)" in merged
        assert "WHEN MATCHED THEN UPDATE SET title = src.title, price = src.price" in merged
        assert "WHEN NOT MATCHED THEN INSERT" in merged

    def test_dm8_upsert_postgres_on_conflict_do_nothing(self, lowerer: DM8DialectLowerer) -> None:
        """Test PostgreSQL ON CONFLICT DO NOTHING lowering to MERGE INTO."""
        pg_sql = (
            "INSERT INTO tags (id, name) VALUES (1, 'tech') "
            "ON CONFLICT (id) DO NOTHING;"
        )
        merged = lowerer.lower_upsert(pg_sql)
        assert merged.startswith("MERGE INTO tags USING")
        assert "ON (tags.id = src.id)" in merged
        assert "WHEN MATCHED" not in merged
        assert "WHEN NOT MATCHED THEN INSERT" in merged


