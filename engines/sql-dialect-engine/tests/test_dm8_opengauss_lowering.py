class TestOpenGaussLowering:
    """Tests for OpenGaussDialectLowerer."""

    @pytest.fixture
    def lowerer(self) -> OpenGaussDialectLowerer:
        return OpenGaussDialectLowerer()

    def test_opengauss_create_table_hash_distribution(self, lowerer: OpenGaussDialectLowerer) -> None:
        """Test openGauss table creation with DISTRIBUTE BY HASH and ORIENTATION."""
        # Table with single primary key
        ddl1 = "CREATE TABLE users (user_id INT PRIMARY KEY, username VARCHAR(50));"
        lowered1 = lowerer.lower_create_table(ddl1)
        assert "WITH (ORIENTATION = ROW)" in lowered1
        assert "DISTRIBUTE BY HASH(user_id)" in lowered1

        # Table without primary key -> uses first column
        ddl2 = "CREATE TABLE logs (msg TEXT, created_at TIMESTAMP);"
        lowered2 = lowerer.lower_create_table(ddl2)
        assert "DISTRIBUTE BY HASH(msg)" in lowered2

        # Explicit distribution column and COLUMN orientation
        ddl3 = "CREATE TABLE metrics (tenant_id VARCHAR(64), metric_val FLOAT);"
        lowered3 = lowerer.lower_create_table(
            ddl3,
            orientation="COLUMN",
            distribute_column="tenant_id",
        )
        assert "WITH (ORIENTATION = COLUMN)" in lowered3
        assert "DISTRIBUTE BY HASH(tenant_id)" in lowered3

    def test_opengauss_data_types(self, lowerer: OpenGaussDialectLowerer) -> None:
        """Test openGauss data type conversions from other engines."""
        # MySQL conversions
        assert "SERIAL" in lowerer.lower_data_types("id INT AUTO_INCREMENT PRIMARY KEY")
        assert "BIGSERIAL" in lowerer.lower_data_types("id BIGINT AUTO_INCREMENT PRIMARY KEY")
        assert "TEXT" in lowerer.lower_data_types("content LONGTEXT")
        assert "TIMESTAMP" in lowerer.lower_data_types("ts DATETIME")
        assert "SMALLINT" in lowerer.lower_data_types("flags TINYINT")

        # Oracle conversions
        assert "NUMERIC" in lowerer.lower_data_types("val NUMBER")
        assert "NUMERIC(10, 2)" in lowerer.lower_data_types("amount NUMBER(10, 2)")
        assert "VARCHAR(100)" in lowerer.lower_data_types("name VARCHAR2(100)")
        assert "TEXT" in lowerer.lower_data_types("doc CLOB")
        assert "BYTEA" in lowerer.lower_data_types("raw_data BLOB")

        # T-SQL conversions
        assert "UUID" in lowerer.lower_data_types("guid UNIQUEIDENTIFIER")
        assert "SERIAL" in lowerer.lower_data_types("id INT IDENTITY(1, 1)")

    def test_opengauss_modes(self) -> None:
        """Test openGauss compatibility modes: PG, A (Oracle), B (MySQL)."""
        # Mode PG (PostgreSQL)
        lowerer_pg = OpenGaussDialectLowerer(mode=OpenGaussMode.PG)
        q_pg = "SELECT IFNULL(col, 'def'), NOW() FROM t"
        lowered_pg = lowerer_pg.lower_query(q_pg)
        assert "COALESCE" in lowered_pg
        assert "CURRENT_TIMESTAMP" in lowered_pg

        # Mode B (MySQL)
        lowerer_b = OpenGaussDialectLowerer(mode=OpenGaussMode.B)
        q_b = "SELECT IFNULL(col, 'def'), NOW() FROM t LIMIT 10, 20"
        lowered_b = lowerer_b.lower_query(q_b)
        assert "LIMIT 20 OFFSET 10" in lowered_b

        # Mode A (Oracle)
        lowerer_a = OpenGaussDialectLowerer(mode=OpenGaussMode.A)
        q_a = "SELECT NVL(col, 'def') FROM t"
        assert "NVL" in lowerer_a.lower_query(q_a)

    def test_opengauss_routine_lowering(self, lowerer: OpenGaussDialectLowerer) -> None:
        """Test openGauss FUNCTION and PROCEDURE envelope lowering."""
        # Function without $$
        func_sql = (
            "CREATE OR REPLACE FUNCTION get_user_count(tenant VARCHAR)\n"
            "RETURNS INTEGER AS\n"
            "BEGIN\n"
            "  RETURN 42;\n"
            "END;\n"
        )
        lowered_func = lowerer.lower_routine(func_sql, routine_type="FUNCTION")
        assert "$$" in lowered_func
        assert "LANGUAGE plpgsql;" in lowered_func

        # Procedure
        proc_sql = (
            "CREATE OR REPLACE PROCEDURE purge_old_records(retention_days INT)\n"
            "AS\n"
            "BEGIN\n"
            "  DELETE FROM logs WHERE created_at < NOW() - retention_days;\n"
            "END;\n"
        )
        lowered_proc = lowerer.lower_routine(proc_sql, routine_type="PROCEDURE")
        assert "$$" in lowered_proc
        assert "LANGUAGE plpgsql;" in lowered_proc


