class TestChinaDBIntegration:
    """Tests for chinadb.py DM8 and openGauss integration."""

    def test_translate_chinadb_ddl_dm8(self) -> None:
        """Test translate_chinadb_ddl for DM8."""
        ddl = "CREATE TABLE customers (id SERIAL PRIMARY KEY, is_vip BOOLEAN, notes TEXT);"
        translated = translate_chinadb_ddl(ddl, "postgres", "dm8", "native")
        assert "INT IDENTITY(1, 1)" in translated["emitted"]
        assert "BIT" in translated["emitted"]
        assert "CLOB" in translated["emitted"]

    def test_translate_chinadb_ddl_opengauss(self) -> None:
        """Test translate_chinadb_ddl for openGauss."""
        ddl = "CREATE TABLE customers (id SERIAL PRIMARY KEY, is_vip BOOLEAN, notes TEXT);"
        translated = translate_chinadb_ddl(ddl, "postgres", "opengauss", "native")
        assert "DISTRIBUTE BY HASH(id)" in translated["emitted"]
        assert "WITH (ORIENTATION = ROW)" in translated["emitted"]

    def test_convenience_functions(self) -> None:
        """Test translate_to_dm8, translate_to_opengauss, lower_to_dm8, lower_to_opengauss."""
        ddl = "CREATE TABLE items (id SERIAL PRIMARY KEY, descr TEXT);"

        # DDL convenience functions
        dm8_ddl = translate_to_dm8(ddl)
        assert "INT IDENTITY(1, 1)" in dm8_ddl["emitted"]
        assert "CLOB" in dm8_ddl["emitted"]

        og_ddl = translate_to_opengauss(ddl)
        assert "DISTRIBUTE BY HASH(id)" in og_ddl["emitted"]

        # Query convenience functions
        q = "SELECT IFNULL(a, b), NOW()"
        dm8_q = lower_to_dm8(q, kind="query")
        assert "NVL(a, b)" in dm8_q
        assert "SYSDATE" in dm8_q
        assert "FROM DUAL" in dm8_q

        og_q = lower_to_opengauss(q, kind="query", mode=OpenGaussMode.PG)
        assert "COALESCE(a, b)" in og_q

    def test_capabilities_and_models(self) -> None:
        """Test ChinaDbDialect enum and capability sets."""
        assert ChinaDbDialect.DM8.value == "dm8"
        assert ChinaDbDialect.OPENGAUSS.value == "opengauss"

        assert "MERGE_UPSERT" in DM8_CAPABILITIES
        assert "CLOB_TEXT" in DM8_CAPABILITIES
        assert "IDENTITY_COLUMNS" in DM8_CAPABILITIES
        assert "HASH_DISTRIBUTION" in OPENGAUSS_CAPABILITIES
        assert "COMPATIBILITY_MODES" in OPENGAUSS_CAPABILITIES
        assert "ROW_ORIENTATION" in OPENGAUSS_CAPABILITIES
        assert "COLUMN_ORIENTATION" in OPENGAUSS_CAPABILITIES
        assert "PLPGSQL_ROUTINES" in OPENGAUSS_CAPABILITIES

        caps = chinadb_capabilities()
        targets = {t["id"]: t for t in caps["targets"]}
        assert "dm8" in targets
        assert "opengauss" in targets
        assert targets["dm8"]["implementationStatus"] == "LOCAL_ADAPTER"
        assert targets["opengauss"]["implementationStatus"] == "LOCAL_ADAPTER"


